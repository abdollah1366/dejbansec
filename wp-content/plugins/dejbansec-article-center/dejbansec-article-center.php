function dejbansec_ac_assets() {
    wp_register_style('dejbansec-article-center', plugins_url('assets/style.css', __FILE__), array(), DEJBANSEC_AC_VERSION);
    wp_register_script('dejbansec-article-center', plugins_url('assets/app.js', __FILE__), array(), DEJBANSEC_AC_VERSION, true);
    if (is_page() || is_single()) {
        wp_enqueue_style('dejbansec-article-center');
        wp_enqueue_script('dejbansec-article-center');
    }
}
add_action('wp_enqueue_scripts', 'dejbansec_ac_assets');

function dejbansec_ac_related($content) {
    if (!is_single() || !in_the_loop() || !is_main_query()) return $content;
    $related = get_posts(array(
        'post_type'=>'post','posts_per_page'=>3,'post__not_in'=>array(get_the_ID()),
        'category__in'=>wp_get_post_categories(get_the_ID()),'orderby'=>'rand'
    ));
    if (!$related) return $content;
    $html = '<div class="djs-related" dir="rtl"><h3>مقالات مرتبط</h3><div class="djs-related-grid">';
    foreach ($related as $p) {
        $html .= '<a href="'.esc_url(get_permalink($p->ID)).'">'.esc_html(get_the_title($p->ID)).'</a>';
    }
    $html .= '</div></div>';
    return $content.$html;
}
add_filter('the_content', 'dejbansec_ac_related');

function dejbansec_ac_admin_notice() {
    if (!current_user_can('manage_options')) return;
    $page_id = intval(get_option('dejbansec_ac_page_id'));
    if ($page_id && get_post_status($page_id)==='publish') return;
    echo '<div class="notice notice-success is-dismissible"><p><strong>مرکز مقالات دژبان‌سک:</strong> برای نمایش فهرست مقالات از شورت‌کد <code>[dejbansec_articles]</code> در یک برگه استفاده کنید.</p></div>';
}
add_action('admin_notices','dejbansec_ac_admin_notice');
