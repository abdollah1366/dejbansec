function dejbansec_ac_activate() {
    $cats = array(
        'امنیت وب' => 'web-security',
        'تست نفوذ' => 'penetration-testing',
        'امنیت شبکه' => 'network-security',
        'امنیت ابری' => 'cloud-security',
        'لینوکس و سرور' => 'linux-server',
        'آموزش امنیت' => 'security-training',
    );

    foreach ($cats as $name => $slug) {
        if (!term_exists($slug, 'category')) {
            wp_insert_term($name, 'category', array('slug' => $slug));
        }
    }

    $articles = dejbansec_ac_articles();
    foreach ($articles as $article) {
        $existing = get_page_by_title($article['title'], OBJECT, 'post');
        if (!$existing) {
            $cat = get_category_by_slug($article['category']);
            wp_insert_post(array(
                'post_title'   => $article['title'],
                'post_content' => $article['content'],
                'post_excerpt' => wp_trim_words(wp_strip_all_tags($article['content']), 34, '…'),
                'post_status'  => 'publish',
                'post_type'    => 'post',
                'post_category'=> $cat ? array($cat->term_id) : array(),
                'tags_input'   => $article['tags'],
            ));
        }
    }

    $page = get_page_by_path('markaz-magalat-dejbansec');
    if (!$page) {
        $page_id = wp_insert_post(array(
            'post_title'   => 'مرکز مقالات دژبان‌سک',
            'post_name'    => 'markaz-magalat-dejbansec',
            'post_content' => '[dejbansec_articles]',
            'post_status'  => 'publish',
            'post_type'    => 'page',
        ));
        if ($page_id && !is_wp_error($page_id)) {
            update_option('dejbansec_ac_page_id', $page_id);
        }
    }
    flush_rewrite_rules();
}
register_activation_hook(__FILE__, 'dejbansec_ac_activate');

