    $posts = get_posts(array('post_type'=>'post','posts_per_page'=>intval($atts['limit']),'post_status'=>'publish','orderby'=>'date','order'=>'DESC'));

    ob_start(); ?>
    <section class="djs-article-center" dir="rtl">
      <div class="djs-head">
        <div>
          <span class="djs-eyebrow">DEJBANSEC KNOWLEDGE CENTER</span>
          <h1>مرکز مقالات امنیت سایبری</h1>
          <p>راهنماهای کاربردی، آموزش‌های تخصصی و مطالب قابل استفاده برای امنیت وب، شبکه، سرور، Cloud و تست نفوذ.</p>
        </div>
        <div class="djs-search"><input id="djsSearch" type="search" placeholder="جستجو در مقالات..."></div>
      </div>
      <div class="djs-filters">
        <button class="active" data-cat="all">همه</button>
        <?php foreach ($cats as $cat): if ($cat->count) : ?>
          <button data-cat="<?php echo esc_attr($cat->slug); ?>"><?php echo esc_html($cat->name); ?></button>
        <?php endif; endforeach; ?>
      </div>
      <div class="djs-grid" id="djsGrid">
        <?php foreach ($posts as $post): $cat = get_the_category($post->ID); $slug = $cat ? $cat[0]->slug : ''; ?>
          <article class="djs-card" data-category="<?php echo esc_attr($slug); ?>" data-title="<?php echo esc_attr(strtolower(get_the_title($post->ID))); ?>">
            <div class="djs-card-top"><span><?php echo $cat ? esc_html($cat[0]->name) : 'امنیت'; ?></span><span><?php echo esc_html(get_the_date('', $post->ID)); ?></span></div>
